//! Repository tasks:
//!
//! ```text
//! cargo xtask generate-udev-rules [--check]
//! cargo xtask install
//! ```
//!
//! `generate-udev-rules` rewrites the shipped udev rule from the device
//! tables in `opp-core`, so the two can never drift apart; `--check`
//! fails instead of writing and is what CI runs. `install` places the
//! binaries and the service files under `$PREFIX` (default `/usr/local`,
//! `$DESTDIR` honoured) and substitutes the prefix into the files that
//! reference it.

use std::env;
use std::fs;
use std::os::unix::fs::PermissionsExt;
use std::path::{Path, PathBuf};
use std::process;

use opp_core::{HidId, SUPPORTED_DIGITIZERS, SUPPORTED_PENS};

/// HID bus type for the internal touch screen digitizer. The leading
/// component of an `/sys/bus/hid/devices` name is the bus id, not a
/// boot-time number: 0018 is HID over I2C.
const HID_BUS_I2C: u16 = 0x0018;
/// HID bus type for the pen, which arrives over Bluetooth. 0005 is
/// HID over Bluetooth (L2CAP).
const HID_BUS_BLUETOOTH: u16 = 0x0005;

fn main() {
    let args: Vec<String> = env::args().skip(1).collect();
    let result = match args.first().map(String::as_str) {
        Some("generate-udev-rules") => generate_udev_rules(args.iter().any(|arg| arg == "--check")),
        Some("install") => install(),
        _ => {
            eprintln!("usage: cargo xtask <generate-udev-rules [--check] | install>");
            process::exit(2);
        }
    };
    if let Err(message) = result {
        eprintln!("xtask: {message}");
        process::exit(1);
    }
}

fn hid_kernel_match(bus: u16, id: HidId) -> String {
    format!("{bus:04X}:{:04X}:{:04X}.*", id.vendor, id.product)
}

/// The complete contents of contrib/udev/70-open-pen-protocol.rules,
/// derived from the supported-device tables.
fn rules_text() -> String {
    let mut text = String::from(
        "# SPDX-License-Identifier: AGPL-3.0-or-later\n\
         # Generated by `cargo xtask generate-udev-rules`; do not edit by hand.\n\
         #\n\
         # Grants the signed-in user access to the pen-related hidraw nodes.\n\
         # TAG+=\"uaccess\" follows the active seat, so no group needs to be\n\
         # maintained. The leading digits of each hid name are the HID bus\n\
         # type (0018 = over I2C, 0005 = over Bluetooth), not a boot number.\n",
    );
    for (id, name) in SUPPORTED_DIGITIZERS {
        text.push_str(&format!(
            "\n# {name}\nSUBSYSTEM==\"hidraw\", KERNELS==\"{}\", TAG+=\"uaccess\"\n",
            hid_kernel_match(HID_BUS_I2C, *id)
        ));
    }
    for (id, name) in SUPPORTED_PENS {
        text.push_str(&format!(
            "\n# {name}\nSUBSYSTEM==\"hidraw\", KERNELS==\"{}\", TAG+=\"uaccess\"\n",
            hid_kernel_match(HID_BUS_BLUETOOTH, *id)
        ));
    }
    text
}

fn generate_udev_rules(check_only: bool) -> Result<(), String> {
    let target = repo_root().join("contrib/udev/70-open-pen-protocol.rules");
    let text = rules_text();
    if check_only {
        let on_disk = match fs::read_to_string(&target) {
            Ok(existing) => existing,
            Err(error) => return Err(format!("{}: {error}", target.display())),
        };
        return if on_disk == text {
            println!("udev rules are up to date");
            Ok(())
        } else {
            Err(format!(
                "{} is stale; run `cargo xtask generate-udev-rules`",
                target.display()
            ))
        };
    }
    if let Some(parent) = target.parent() {
        fs::create_dir_all(parent).map_err(|error| format!("{}: {error}", parent.display()))?;
    }
    fs::write(&target, text).map_err(|error| format!("{}: {error}", target.display()))?;
    println!("wrote {}", target.display());
    Ok(())
}

fn install() -> Result<(), String> {
    let prefix = env_or("PREFIX", "/usr/local");
    let destdir = env::var("DESTDIR").unwrap_or_default();
    let bindir = env_or("BINDIR", &format!("{prefix}/bin"));
    let libexecdir = env_or("LIBEXECDIR", &format!("{prefix}/libexec"));
    let udev_rules_dir = env_or("UDEVRULESDIR", &format!("{prefix}/lib/udev/rules.d"));
    let dbus_system_services_dir = env_or(
        "DBUS_SYSTEM_SERVICES_DIR",
        &format!("{prefix}/share/dbus-1/system-services"),
    );
    let dbus_system_policy_dir = env_or(
        "DBUS_SYSTEM_POLICY_DIR",
        &format!("{prefix}/share/dbus-1/system.d"),
    );
    let dbus_session_services_dir = env_or(
        "DBUS_SESSION_SERVICES_DIR",
        &format!("{prefix}/share/dbus-1/services"),
    );
    let polkit_action_dir = env_or(
        "POLKIT_ACTION_DIR",
        &format!("{prefix}/share/polkit-1/actions"),
    );
    let systemd_system_unit_dir = env_or(
        "SYSTEMD_SYSTEM_UNIT_DIR",
        &format!("{prefix}/lib/systemd/system"),
    );
    let systemd_user_unit_dir = env_or(
        "SYSTEMD_USER_UNIT_DIR",
        &format!("{prefix}/lib/systemd/user"),
    );
    let systemd_user_preset_dir = env_or(
        "SYSTEMD_USER_PRESET_DIR",
        &format!("{prefix}/lib/systemd/user-preset"),
    );

    let root = repo_root();
    let data = root.join("data");
    let target_dir = env::var("CARGO_TARGET_DIR")
        .map(PathBuf::from)
        .unwrap_or_else(|_| root.join("target/release"));

    for (binary, dir) in [
        ("oppd", &bindir),
        ("oppctl", &bindir),
        ("opp-settings", &bindir),
        ("opp-pair-helper", &libexecdir),
    ] {
        install_binary(&target_dir.join(binary), &staged(&destdir, dir))?;
    }

    install_file(
        &root.join("contrib/udev/70-open-pen-protocol.rules"),
        &staged(&destdir, &udev_rules_dir),
        0o644,
        None,
    )?;
    install_file(
        &data.join("dbus/system-services/org.openpenprotocol.PairHelper1.service"),
        &staged(&destdir, &dbus_system_services_dir),
        0o644,
        Some(&prefix),
    )?;
    install_file(
        &data.join("dbus/system.d/org.openpenprotocol.PairHelper1.conf"),
        &staged(&destdir, &dbus_system_policy_dir),
        0o644,
        None,
    )?;
    install_file(
        &data.join("dbus/session-services/org.openpenprotocol.Daemon1.service"),
        &staged(&destdir, &dbus_session_services_dir),
        0o644,
        Some(&prefix),
    )?;
    install_file(
        &data.join("polkit/org.openpenprotocol.policy"),
        &staged(&destdir, &polkit_action_dir),
        0o644,
        None,
    )?;
    install_file(
        &data.join("systemd/system/opp-pair-helper.service"),
        &staged(&destdir, &systemd_system_unit_dir),
        0o644,
        Some(&prefix),
    )?;
    install_file(
        &data.join("systemd/user/oppd.service"),
        &staged(&destdir, &systemd_user_unit_dir),
        0o644,
        Some(&prefix),
    )?;
    install_file(
        &data.join("systemd/user-preset/80-open-pen-protocol.preset"),
        &staged(&destdir, &systemd_user_preset_dir),
        0o644,
        None,
    )?;

    // Settings window entry and icon, next to where buildRustPackage
    // already puts them from the crate's own data directory.
    let settings_data = root.join("crates/opp-settings/data");
    install_file(
        &settings_data.join("org.openpenprotocol.Settings.desktop"),
        &staged(&destdir, &format!("{prefix}/share/applications")),
        0o644,
        Some(&prefix),
    )?;
    install_file(
        &settings_data.join("icons/hicolor/scalable/apps/org.openpenprotocol.Settings.svg"),
        &staged(
            &destdir,
            &format!("{prefix}/share/icons/hicolor/scalable/apps"),
        ),
        0o644,
        None,
    )?;

    println!();
    println!("Installed under {destdir}{prefix}. If udev is running:");
    println!("  udevadm control --reload-rules && udevadm trigger");
    println!("Then apply the user preset once, so oppd starts with every session:");
    println!("  systemctl --global preset oppd.service");
    println!("(distro packaging macros do this on install). The pairing helper");
    println!("needs nothing: the system bus activates it when first called.");
    Ok(())
}

/// The repo root, resolved from this crate's manifest location so the
/// task works from any working directory.
fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(Path::parent)
        .expect("xtask lives in crates/xtask")
        .to_path_buf()
}

fn env_or(name: &str, fallback: &str) -> String {
    match env::var(name) {
        Ok(value) if !value.is_empty() => value,
        _ => fallback.to_string(),
    }
}

/// DESTDIR staging: the file lands under {DESTDIR}{dir} while the
/// installed contents still reference the plain prefix.
fn staged(destdir: &str, dir: &str) -> PathBuf {
    Path::new(destdir).join(dir.trim_start_matches('/'))
}

fn install_binary(source: &Path, dir: &Path) -> Result<(), String> {
    fs::create_dir_all(dir).map_err(|error| format!("{}: {error}", dir.display()))?;
    let dest = dir.join(
        source
            .file_name()
            .ok_or_else(|| format!("{} has no file name", source.display()))?,
    );
    fs::copy(source, &dest).map_err(|error| {
        format!(
            "{} -> {}: {error} (build first with `cargo build --release --locked --workspace`)",
            source.display(),
            dest.display()
        )
    })?;
    fs::set_permissions(&dest, fs::Permissions::from_mode(0o755))
        .map_err(|error| format!("{}: {error}", dest.display()))?;
    println!("  install {}", dest.display());
    Ok(())
}

fn install_file(source: &Path, dir: &Path, mode: u32, prefix: Option<&str>) -> Result<(), String> {
    fs::create_dir_all(dir).map_err(|error| format!("{}: {error}", dir.display()))?;
    let dest = dir.join(
        source
            .file_name()
            .ok_or_else(|| format!("{} has no file name", source.display()))?,
    );
    let mut body =
        fs::read_to_string(source).map_err(|error| format!("{}: {error}", source.display()))?;
    if let Some(prefix) = prefix {
        body = body.replace("@PREFIX@", prefix);
    }
    fs::write(&dest, body).map_err(|error| format!("{}: {error}", dest.display()))?;
    fs::set_permissions(&dest, fs::Permissions::from_mode(mode))
        .map_err(|error| format!("{}: {error}", dest.display()))?;
    println!("  install {}", dest.display());
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rules_cover_the_digitizer_and_the_pen() {
        let rules = rules_text();
        assert!(rules.contains("0018:04F3:4631.*"));
        assert!(rules.contains("0005:330A:0001.*"));
        assert!(rules.contains("uaccess"));
    }

    #[test]
    fn rules_are_stable_across_runs() {
        assert_eq!(rules_text(), rules_text());
    }

    /// The bus only reads activation files named after the bus name they
    /// declare plus `.service` (dbus-daemon(1), `<servicedir>`); any other
    /// name is silently skipped and the service never starts.
    #[test]
    fn dbus_activation_files_are_named_after_their_bus_name() {
        let data = repo_root().join("data/dbus");
        let mut checked = 0;
        for dir in ["system-services", "session-services"] {
            for entry in fs::read_dir(data.join(dir)).expect("activation dir") {
                let path = entry.expect("dir entry").path();
                let body = fs::read_to_string(&path).expect("activation file");
                let name = body
                    .lines()
                    .find_map(|line| line.strip_prefix("Name="))
                    .expect("a Name= line");
                let file = path
                    .file_name()
                    .and_then(|f| f.to_str())
                    .expect("utf-8 name");
                assert_eq!(file, format!("{name}.service"), "{}", path.display());
                checked += 1;
            }
        }
        assert_eq!(checked, 2, "one system and one session activation file");
    }
}
